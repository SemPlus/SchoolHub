
import { t } from './i18n';// Official list of Italian lower- and upper-secondary schools, generated by
// scripts/build-schools.mjs from the Ministry of Education open data. Picking
// a school from this list (instead of typing it) is what prevents the same
// school from being stored under several spellings.

export interface SchoolOption {
  /** Official school code (codice meccanografico). */
  id: string;
  name: string;
  type: string;
  city: string;
  province: string;
  /** 1 = lower secondary, 2 = upper secondary. */
  grade: 1 | 2;
  parent?: string;
}

interface SchoolsFile {
  schoolYear: string;
  types: string[];
  provinces: string[];
  schools: [string, string, number, string, number, 1 | 2, string?][];
}

interface IndexedSchool {
  school: SchoolOption;
  haystack: string;
}

let loading: Promise<IndexedSchool[]> | null = null;

export function normalizeText(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function loadSchools(): Promise<IndexedSchool[]> {
  if (!loading) {
    loading = fetch('/schools.json')
      .then(response => {
        if (!response.ok) throw new Error(t("Could not load the school list (HTTP {0}).", response.status));
        return response.json() as Promise<SchoolsFile>;
      })
      .then(file => file.schools.map(([id, name, typeIndex, city, provinceIndex, grade, parent]) => {
        const school: SchoolOption = {
          id,
          name,
          type: file.types[typeIndex] ?? '',
          city,
          province: file.provinces[provinceIndex] ?? '',
          grade,
          parent,
        };
        return {
          school,
          haystack: normalizeText([name, parent, city, school.province, school.type, id].filter(Boolean).join(' ')),
        };
      }))
      .catch(error => {
        // Allow a retry after a network failure.
        loading = null;
        throw error;
      });
  }
  return loading;
}

/**
 * Every word typed must appear somewhere in the school's name, institute,
 * city, province, type or code. Results whose name starts with the query
 * come first.
 */
export async function searchSchools(query: string, limit = 30): Promise<SchoolOption[]> {
  const words = normalizeText(query).split(' ').filter(Boolean);
  if (words.length === 0) return [];
  const all = await loadSchools();
  const matches: { school: SchoolOption; score: number }[] = [];
  for (const entry of all) {
    if (!words.every(word => entry.haystack.includes(word))) continue;
    const name = normalizeText(entry.school.name);
    const score = (name.startsWith(words[0]) ? 0 : 2) + (normalizeText(entry.school.city).includes(words[words.length - 1]) ? 0 : 1);
    matches.push({ school: entry.school, score });
    if (matches.length > 2000) break;
  }
  matches.sort((a, b) => a.score - b.score || a.school.name.localeCompare(b.school.name, 'it'));
  return matches.slice(0, limit).map(m => m.school);
}

export function describeSchool(school: Pick<SchoolOption, 'type' | 'city' | 'province'>): string {
  const place = school.province && school.province !== school.city ? `${school.city} (${school.province})` : school.city;
  return [school.type, place].filter(Boolean).join(' · ');
}

/** Look a school up by its official code, e.g. from a class poster link. */
export async function findSchoolById(id: string): Promise<SchoolOption | null> {
  const all = await loadSchools();
  return all.find(entry => entry.school.id === id.toUpperCase())?.school ?? null;
}
